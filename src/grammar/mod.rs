/// An event code: one to three parts (module documentation).
///
/// ```
/// use exi::grammar::EventCode;
/// let c = EventCode::new(&[2, 1]);
/// assert_eq!((c.parts(), c.len()), (&[2, 1][..], 2));
/// assert_eq!(c.to_string(), "2.1");
/// assert_eq!(EventCode::new(&[0]).to_string(), "0");
/// ```
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct EventCode {
    parts: [u32; 3],
    len: u8,
}

impl EventCode {
    /// # Panics
    ///
    /// When `parts` is empty or longer than 3: codes are built only by
    /// grammar code.
    pub const fn new(parts: &[u32]) -> Self {
        assert!(
            !parts.is_empty() && parts.len() <= 3,
            "an event code has 1 to 3 parts"
        );
        let mut p = [0u32; 3];
        let mut i = 0;
        while i < parts.len() {
            p[i] = parts[i];
            i += 1;
        }
        EventCode { parts: p, len: parts.len() as u8 }
    }
    pub fn parts(&self) -> &[u32] {
        &self.parts[..self.len as usize]
    }
    #[allow(clippy::len_without_is_empty)] // a code always has 1 to 3 parts
    pub const fn len(&self) -> u8 {
        self.len
    }
}

/// `a`, `a.b` or `a.b.c`.
impl core::fmt::Display for EventCode {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        for (i, p) in self.parts().iter().enumerate() {
            if i > 0 {
                f.write_str(".")?;
            }
            write!(f, "{p}")?;
        }
        Ok(())
    }
}

/// The terminal symbol of a production: the kind of event it matches.
///
/// `SE(n)` and `AT(n)` match one name; `SeUri(u)` and `AtUri(u)` any
/// name in the namespace with URI number `u` (a wildcard limited to
/// namespaces); `SeAny` and `AtAny` any name.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum Terminal {
    SD,
    ED,
    SE(NameId),
    SeUri(u32),
    SeAny,
    EE,
    AT(NameId),
    AtUri(u32),
    AtAny,
    CH,
    NS,
    CM,
    PI,
    DT,
    ER,
    SC,
}

/// Counts describing a grammar set.
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq)]
pub struct GrammarStats {
    pub element_declarations: u32,
    pub type_grammars: u32,
    pub states: u32,
    pub productions: u32,
    pub simple_types: u32,
    pub names: u32,
}

/// Grammars and initial string-table entries. Immutable; `Send + Sync`;
/// share it with `Arc` across threads.
///
/// ```
/// use exi::grammar::GrammarSet;
/// let g = GrammarSet::schemaless();
/// assert!(!g.is_schema_informed());
/// assert_eq!(g.initial_entries().uris().len(), 3);
/// assert_eq!(g.name_id("http://www.w3.org/XML/1998/namespace", "lang"),
///            Some(exi::NameId { uri: 1, local: 2 }));
/// assert_eq!(g.name_id("", "anything"), None);
/// assert!(!g.is_closed());                        // schema-less accepts any name
/// fn shareable<T: Send + Sync>() {}
/// shareable::<GrammarSet>();
/// ```
pub struct GrammarSet {
    entries: InitialEntries,
    pub(crate) schema: Option<informed::Schema>,
}

impl GrammarSet {
    /// No schema: built-in grammars only (`schemaId` nil).
    pub fn schemaless() -> GrammarSet {
        GrammarSet { entries: InitialEntries::schemaless(), schema: None }
    }
    /// Starts a schema-informed grammar set built in code (see
    /// [`informed`]).
    pub fn builder() -> informed::GrammarBuilder {
        informed::GrammarBuilder::new()
    }
    pub fn is_schema_informed(&self) -> bool {
        self.schema.is_some()
    }
    pub fn initial_entries(&self) -> &InitialEntries {
        &self.entries
    }
    /// The fixed numbers of a name among the initial entries: the same
    /// in every session that uses this grammar set, so they can be
    /// looked up once and compared as integers.
    pub fn name_id(&self, uri: &str, local: &str) -> Option<NameId> {
        let u = self.entries.uris().iter().position(|x| *x == uri)? as u32;
        let l =
            self.entries.locals(u).iter().position(|x| *x == local)? as u32;
        Some(NameId { uri: u, local: l })
    }
    /// True when the grammars accept no name they do not declare:
    /// schema-informed, and no wildcard anywhere.
    pub fn is_closed(&self) -> bool {
        self.schema.as_ref().is_some_and(|s| s.closed)
    }
    pub fn stats(&self) -> GrammarStats {
        let names = (0..self.entries.uris().len() as u32)
            .map(|u| self.entries.locals(u).len() as u32)
            .sum();
        match &self.schema {
            None => GrammarStats { names, ..GrammarStats::default() },
            Some(s) => GrammarStats {
                element_declarations: s.elements.len() as u32,
                type_grammars: s.types.len() as u32,
                states: s.types.iter().map(|t| t.states.len() as u32).sum(),
                productions: s
                    .types
                    .iter()
                    .flat_map(|t| &t.states)
                    .map(|st| st.len() as u32)
                    .sum(),
                simple_types: s.simple.len() as u32,
                names,
            },
        }
    }
    /// Interns the initial entries into `strings`, ready for sessions.
    ///
    /// # Errors
    ///
    /// `ErrorKind::Limit` when `strings` cannot take them.
    pub fn attach<'g>(
        &'g self,
        strings: &'g GlobalStrings,
    ) -> Result<Grammars<'g>> {
        Ok(Grammars {
            set: self,
            initial: self.entries.attach(strings)?,
            #[cfg(feature = "std")]
            tables: Default::default(),
            #[cfg(feature = "std")]
            tops: Default::default(),
        })
    }
}

/// What a built code table is for: the type and state, the start-tag
/// flags, and the options that shape it (strictness, and which of NS,
/// SC, DTD, CM and PI are kept).
#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]
pub(crate) struct TableKey {
    pub ty: u32,
    pub state: u32,
    pub flags: u16,
}

/// Code tables built from a schema state on demand (the states of
/// non-strict grammars, and first start tags with `xsi:type` or
/// `xsi:nil`), shared by every stream using these grammars.
pub(crate) type TableCache = hashbrown::HashMap<
    TableKey,
    alloc::sync::Arc<builtin::CodeTable>,
    rustc_hash::FxBuildHasher,
>;

#[cfg(feature = "std")]
type TopCache = hashbrown::HashMap<
    (bool, bool, builtin::Keep),
    alloc::sync::Arc<crate::engine::TopTables>,
    rustc_hash::FxBuildHasher,
>;

/// A grammar set attached to global string tables: what readers and
/// writers borrow. Create one per grammar set and global tables, and
/// share it among any number of sessions.
pub struct Grammars<'g> {
    set: &'g GrammarSet,
    initial: Initial<'g>,
    #[cfg(feature = "std")]
    tables: std::sync::Mutex<TableCache>,
    #[cfg(feature = "std")]
    tops: std::sync::Mutex<TopCache>,
}

impl<'g> Grammars<'g> {
    pub fn set(&self) -> &'g GrammarSet {
        self.set
    }
    pub fn initial(&self) -> &Initial<'g> {
        &self.initial
    }
    #[cfg(feature = "std")]
    pub(crate) fn table_cache(&self) -> &std::sync::Mutex<TableCache> {
        &self.tables
    }
    #[cfg(feature = "std")]
    pub(crate) fn top_tables(
        &self,
        opts: &crate::Options,
        keep: builtin::Keep,
    ) -> alloc::sync::Arc<crate::engine::TopTables> {
        // Only DT, CM and PI can change top-level productions.
        let keep = builtin::Keep { ns: false, sc: false, ..keep };
        let key = (opts.fragment(), opts.strict(), keep);
        let mut tops = self.tops.lock().unwrap_or_else(|e| e.into_inner());
        tops.entry(key)
            .or_insert_with(|| {
                alloc::sync::Arc::new(crate::engine::TopTables::new(
                    self.set.schema.as_ref(),
                    opts,
                    keep,
                ))
            })
            .clone()
    }

    pub fn strings(&self) -> &'g GlobalStrings {
        self.initial.global()
    }
}

/// Shows the counts, not the tables.
impl core::fmt::Debug for GrammarSet {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("GrammarSet")
            .field("schema_informed", &self.is_schema_informed())
            .field("stats", &self.stats())
            .finish()
    }
}
