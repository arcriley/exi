//! # What a grammar does
//!
//! At every point of a stream the reader and writer are in a grammar
//! state. The state's productions list the events allowed next, each
//! with an **event code** of one to three parts, and the state each
//! leads to. The writer writes the code of the event it is given; the
//! reader reads a code and so learns which event follows. Both sides
//! hold the same grammars, so the codes mean the same thing to both.
//!
//! # Event codes
//!
//! An event code is one to three parts, written `a`, `a.b` or `a.b.c`.
//! The productions of one state are numbered so that, at each level,
//! the values used are `0 .. count`. Each part is an n-bit value of
//! `width(count)` bits, where `count` is the number of distinct
//! values that part takes among the productions sharing the earlier
//! parts. A level with a single value takes no bits. (See
//! [`crate::coding::width`] and
//! [`crate::coding::datatypes::write_event_code`].)
//!
//! Example: a state whose productions have the codes `0`, `1`, `2.0`,
//! `2.1` writes the first part with `width(3) = 2` bits, and the second
//! part, after a first part of 2, with `width(2) = 1` bit.
//!
//! # Kinds of grammar
//!
//! | Kind | Module | Changes during a stream |
//! |---|---|---|
//! | Built-in (schema-less) | [`builtin`] | yes: element grammars learn productions as names are met |
//! | Schema-informed | [`informed`] | no |
//!
//! A [`GrammarSet`] holds the schema-informed grammars of a schema (or
//! none, for schema-less streams) and the initial string-table entries
//! that go with them. Readers and writers keep the built-in grammars
//! they learn in their own session.
//!
//! # Pruning by options
//!
//! Productions for the event kinds an options set does not keep are
//! removed before codes are assigned, and the remaining codes are
//! renumbered to stay contiguous:
//!
//! | Production | Kept when |
//! |---|---|
//! | NS | `Preserve.prefixes` |
//! | SC | `selfContained` |
//! | DT, ER | `Preserve.dtd` |
//! | CM | `Preserve.comments` |
//! | PI | `Preserve.pis` |
//!
//! `strict` removes all of these from schema-informed grammars (the
//! options rules already forbid keeping them under strict).
//!
//! # Support in this build
//!
//! | Stream | Status |
//! |---|---|
//! | Schema-less (`schemaId` nil or absent with [`GrammarSet::schemaless`]) | supported |
//! | Schema-informed, `strict` | supported |
//! | Schema-informed, not strict (undeclared productions, element fragment grammars) | `ErrorKind::Unsupported` for now |
//! | `schemaId` "" (built-in types only) | `ErrorKind::Unsupported` for now |

